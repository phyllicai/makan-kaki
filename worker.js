// Cloudflare Workers entry: same API + UI as server.js, serverless.
// Build: node scripts/build-worker.js && npx wrangler deploy (see wrangler.toml). Secrets: wrangler secret put QLOO_API_KEY
import { makeQloo } from './src/qloo/index.js';
import { makeLLM } from './src/agent/llm.js';
import { runAgent } from './src/agent/agent.js';
import { COURTS, SAMPLE_GROUP } from './src/data/courts.js';
import { INDEX, APP, CSS } from './src/static.gen.js'; // generated by scripts/build-worker.js

const STATIC = {
  '/': [INDEX, 'text/html; charset=utf-8'],
  '/index.html': [INDEX, 'text/html; charset=utf-8'],
  '/app.js': [APP, 'text/javascript'],
  '/styles.css': [CSS, 'text/css'],
};
const json = (code, obj) => new Response(JSON.stringify(obj), { status: code, headers: { 'content-type': 'application/json' } });
const hits = new Map();
function limited(ip) { const now = Date.now(); const arr = (hits.get(ip) || []).filter(t => now - t < 60000); arr.push(now); hits.set(ip, arr); return arr.length > 20; }

export default {
  async fetch(req, env) {
    const url = new URL(req.url);
    const qloo = makeQloo(env || {});
    const llm = makeLLM(env || {});
    try {
      if (url.pathname === '/api/health') return json(200, { ok: true, qloo: qloo.mode, llm: llm ? llm.model : null });
      if (url.pathname === '/api/config') return json(200, { courts: COURTS, sample: SAMPLE_GROUP, mode: qloo.mode, llm: llm ? llm.model : null });
      if (url.pathname === '/api/plan' && req.method === 'POST') {
        if (limited(req.headers.get('cf-connecting-ip') || 'x')) return json(429, { error: 'Too many requests, try again in a minute.' });
        const body = await req.text();
        if (body.length > 50000) return json(413, { error: 'Too large' });
        return json(200, await runAgent(JSON.parse(body || '{}'), { qloo, llm }));
      }
      const s = STATIC[url.pathname];
      if (s) return new Response(s[0], { headers: { 'content-type': s[1] } });
      return json(404, { error: 'not found' });
    } catch (e) {
      console.error(e);
      return json(e.status === 401 ? 502 : 500, { error: e.message });
    }
  },
};
